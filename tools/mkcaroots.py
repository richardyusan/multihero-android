"""
Write runtime/net/ca_roots.inc: the Mozilla root certificates (cacert.pem of the "certifi"
package) as a C string, used by the native builds for wss:// (runtime/net/ws_client.cpp).

    pip download certifi --no-deps -d /tmp/c && python3 tools/mkcaroots.py /tmp/c/certifi-*.whl
"""
import os
import sys
import zipfile

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def main():
    src = sys.argv[1] if len(sys.argv) > 1 else None
    if not src:
        print(__doc__)
        sys.exit(1)
    if src.endswith(".whl"):
        with zipfile.ZipFile(src) as z:
            pem = z.read("certifi/cacert.pem").decode("ascii")
            version = os.path.basename(src).split("-")[1]
    else:
        pem = open(src, encoding="ascii").read()
        version = "?"
    lines = [l for l in pem.splitlines() if not l.startswith("#") and l.strip()]
    n = sum(1 for l in lines if l.startswith("-----BEGIN CERTIFICATE"))
    out = os.path.join(HERE, "runtime", "net", "ca_roots.inc")
    with open(out, "w", encoding="ascii", newline="\n") as fh:
        fh.write("// Generated by tools/mkcaroots.py - %d root certificates of the Mozilla CA list\n" % n)
        fh.write("// (certifi %s, https://github.com/certifi/python-certifi, MPL-2.0). Do not edit.\n" % version)
        fh.write("static const char MH_CA_PEM[] =\n")
        for l in lines:
            fh.write('"%s\\n"\n' % l)
        fh.write(";\n")
    print("%s: %d certificates" % (out, n))


if __name__ == "__main__":
    main()
